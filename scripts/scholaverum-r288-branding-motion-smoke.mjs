import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base=(process.argv[2]||'http://127.0.0.1:10000').replace(/\/$/,'');
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'no-preference'});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 const svg=await page.request.get(base+'/scholaverum-orbital-emblem-r288.svg?brand=r288',{timeout:30000});
 assert.equal(svg.status(),200,'approved orbital SVG must be shipped in production image');
 const graphic=await svg.text();
 assert.match(graphic,/<ellipse/,'quiet orbital rings are present');
 assert.ok(graphic.includes('data:image/png;base64,'),'the original official logo is embedded in the emblem');
 assert.doesNotMatch(graphic,/LEARN[ .·•]+CREATE[ .·•]+GROW/i,'approved emblem must not contain the tagline');
 await page.goto(base+'/#dashboard',{waitUntil:'domcontentloaded',timeout:45000});
 await page.waitForSelector('[data-workspace-layout="r285"] .v288-orbit-emblem img',{state:'visible',timeout:30000});
 const dashboard=await page.evaluate(async()=>{
  const root=document.querySelector('[data-workspace-layout="r285"]');
  const wrapper=root?.querySelector('.v288-orbit-emblem'),img=wrapper?.querySelector('img');
  await img?.decode();
  const rect=wrapper?.getBoundingClientRect();
  return {src:img?.getAttribute('src'),imageWidth:img?.naturalWidth,width:rect?.width,height:rect?.height,hidden:getComputedStyle(wrapper).display==='none',legacyCaption:root?.querySelectorAll('.v285-orbit-caption').length,orbitCount:root?.querySelectorAll('.v288-orbit-emblem').length};
 });
 assert.equal(dashboard.src,'/scholaverum-orbital-emblem-r288.svg');
 assert.ok(dashboard.imageWidth>0&&dashboard.width>=170&&dashboard.height>=150&&!dashboard.hidden,'desktop orbital emblem must render clearly');
 assert.equal(dashboard.legacyCaption,0,'no Learn Create Grow line underneath the new emblem');
 assert.equal(dashboard.orbitCount,1,'only one canonical orbital brand');
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(150);
 const small=await page.evaluate(()=>{const el=document.querySelector('.v288-orbit-emblem'),rect=el.getBoundingClientRect();return {display:getComputedStyle(el).display,width:rect.width,height:rect.height,client:document.querySelector('#v51-main').clientWidth,scroll:document.querySelector('#v51-main').scrollWidth}});
 assert.ok(small.display!=='none'&&small.width>=100&&small.height>=100,'mobile Dashboard logo must remain visible');
 assert.ok(small.scroll<=small.client+4,'Dashboard branding must not trigger horizontal overflow');
 await page.setViewportSize({width:1440,height:900});
 await page.goto(base+'/#home',{waitUntil:'domcontentloaded',timeout:45000});
 await page.waitForSelector('#v280-editorial-home .v288-sphere-spin',{state:'visible',timeout:30000});
 const spin=await page.evaluate(async()=>{
  const sphere=document.querySelector('#v280-editorial-home .v280-planet.v288-branded-sphere');
  const rot=sphere?.querySelector('.v288-sphere-spin');
  const logoImages=[...rot.querySelectorAll('img')];
  await Promise.all(logoImages.map(i=>i.decode()));
  return {sphereCount:document.querySelectorAll('.v288-branded-sphere').length,logoImages:logoImages.length,paths:logoImages.map(i=>i.getAttribute('src')),natural:logoImages.every(i=>i.naturalWidth>0),anim:getComputedStyle(rot).animationName,duration:getComputedStyle(rot).animationDuration,play:getComputedStyle(rot).animationPlayState,heroOverflow:getComputedStyle(document.querySelector('.v280-hero')).overflowX};
 });
 assert.equal(spin.sphereCount,1,'only one hero branded sphere');
 assert.equal(spin.logoImages,2,'front and back bear the original SCHOLAVERUM logo');
 assert.ok(spin.paths.every(p=>p==='/scholaverum-logo-r246.png')&&spin.natural);
 assert.match(spin.anim,/v288SphereSpin/,'the orb turns without being static');
 assert.equal(spin.duration,'22s','gentle one-turn-per-22-seconds rotation');
 assert.equal(spin.play,'running','rotation must begin on the homepage automatically');
 assert.equal(spin.heroOverflow,'hidden','rotating ball remains inside hero section');
 const before=await page.locator('.v288-sphere-spin').evaluate(el=>getComputedStyle(el).transform);
 await page.waitForTimeout(200);
 const after=await page.locator('.v288-sphere-spin').evaluate(el=>getComputedStyle(el).transform);
 assert.notEqual(before,after,'the ball really rotates between animation frames');
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(120);
 assert.equal(await page.locator('.v280-planet.v288-branded-sphere').count(),1);
 assert.equal(await page.locator('.v288-sphere-spin').evaluate(el=>getComputedStyle(el).animationDuration),'25s','mobile orb uses lower-motion 25-second rotation');
 const reduce=await browser.newPage({viewport:{width:1100,height:800},reducedMotion:'reduce'});
 await reduce.goto(base+'/#home',{waitUntil:'domcontentloaded',timeout:45000});
 await reduce.waitForSelector('.v288-sphere-spin',{state:'attached',timeout:30000});
 const reduced=await reduce.locator('.v288-sphere-spin').evaluate(el=>getComputedStyle(el).animationName);
 assert.equal(reduced,'none','reduced-motion preference must disable automatic sphere rotation');
 await reduce.close();
 assert.deepEqual(errors,[],'branding must have no uncaught browser errors');
 console.log('PASS r288 branding: original logo embedded in quiet orbital SVG, no tagline, visible mobile Dashboard emblem, 22s rotating branded sphere and reduced motion');
}finally{await browser.close()}
